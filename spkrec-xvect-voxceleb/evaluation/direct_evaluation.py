#!/usr/bin/env python3
"""
Evaluation script for PGD Attack on SpeechBrain Speaker Verification Model
This script evaluates the effectiveness of adversarial examples generated by pgd_attack.py
"""

import torch
import torchaudio
import numpy as np
import os
import argparse
from tqdm import tqdm
from speechbrain.inference import EncoderClassifier
from scipy.spatial.distance import cosine
import matplotlib.pyplot as plt
import pandas as pd

def load_audio(file_path, audio_dir=None, sample_rate=16000):
    """Load audio file and resample if necessary"""
    # Handle path construction - allow for both relative and absolute paths
    if audio_dir is not None and not os.path.isabs(file_path):
        # If path already contains audio_dir, don't add it again
        if not file_path.startswith(audio_dir):
            file_path = os.path.join(audio_dir, file_path)
    
    # Check if file exists
    if not os.path.exists(file_path):
        raise FileNotFoundError(f"Audio file not found: {file_path}")
        
    # Load and resample audio
    waveform, sr = torchaudio.load(file_path)
    if sr != sample_rate:
        waveform = torchaudio.functional.resample(waveform, sr, sample_rate)
    return waveform

def compute_snr(original, adversarial):
    """Compute Signal-to-Noise Ratio between original and adversarial waveforms"""
    original = original.numpy().flatten()
    adversarial = adversarial.numpy().flatten()
    noise = adversarial - original
    
    signal_power = np.sum(original ** 2)
    noise_power = np.sum(noise ** 2)
    
    if noise_power == 0:
        return float('inf')
    
    snr = 10 * np.log10(signal_power / noise_power)
    return snr

def calculate_eer(labels, scores):
    """
    Calculate Equal Error Rate (EER)
    
    Args:
        labels: Ground truth labels (0 for different speakers, 1 for same speaker)
        scores: Similarity scores
    
    Returns:
        EER value and threshold at which EER occurs
    """
    # Sort scores and corresponding labels
    indices = np.argsort(scores)
    labels = np.array(labels)[indices]
    scores = np.array(scores)[indices]
    
    # Calculate false accept rate (FAR) and false reject rate (FRR)
    far = []
    frr = []
    thresholds = []
    
    for threshold in scores:
        thresholds.append(threshold)
        
        # FAR: False Accept Rate (different speakers classified as same)
        far_val = np.sum((scores >= threshold) & (labels == 0)) / np.sum(labels == 0)
        far.append(far_val)
        
        # FRR: False Reject Rate (same speakers classified as different)
        frr_val = np.sum((scores < threshold) & (labels == 1)) / np.sum(labels == 1)
        frr.append(frr_val)
    
    # Convert to numpy arrays
    far = np.array(far)
    frr = np.array(frr)
    
    # Find the threshold where FAR = FRR
    abs_diff = np.abs(far - frr)
    min_index = np.argmin(abs_diff)
    eer = (far[min_index] + frr[min_index]) / 2
    eer_threshold = thresholds[min_index]
    
    return eer, eer_threshold

def evaluate_attack(model, pairs_file, audio_dir="data/wav", adv_dir="adversarial_examples", device="cuda", threshold=0.5, max_pairs=None):
    """
    Evaluate the effectiveness of adversarial examples
    
    Args:
        model: SpeechBrain EncoderClassifier model
        pairs_file: File containing verification pairs
        audio_dir: Directory containing original audio files
        adv_dir: Directory containing adversarial examples
        device: Device to run the evaluation on
        threshold: Similarity threshold for verification
        max_pairs: Maximum number of pairs to evaluate
    
    Returns:
        Dictionary containing evaluation metrics
    """
    original_correct = 0
    adv_correct = 0
    adv_successful = 0
    total_pairs = 0
    snr_values = []
    
    # For EER calculation
    original_labels = []
    original_scores = []
    adversarial_labels = []
    adversarial_scores = []
    
    # Create results dataframe
    results = {
        'pair_id': [],
        'label': [],
        'file1': [],
        'file2': [],
        'original_similarity': [],
        'adversarial_similarity': [],
        'original_prediction': [],
        'adversarial_prediction': [],
        'attack_success': [],
        'snr': []
    }
    
    # Load verification pairs
    with open(pairs_file, 'r') as f:
        pairs = f.readlines()
    
    # Limit pairs if max_pairs is specified
    if max_pairs is not None:
        pairs = pairs[:max_pairs]
        print(f"Evaluating only the first {max_pairs} pairs for testing")
    
    for i, pair in enumerate(tqdm(pairs)):
        parts = pair.strip().split()
        label = int(parts[0])
        file1 = parts[1]
        file2 = parts[2]
        
        # Construct paths
        adv_file_dir = os.path.dirname(file1)
        adv_file_basename = os.path.basename(file1)
        adv_path1 = os.path.join(adv_dir, adv_file_dir, f"adv_{adv_file_basename}")
        
        # Skip if adversarial example doesn't exist
        if not os.path.exists(adv_path1):
            print(f"Skipping pair - adversarial example not found: {adv_path1}")
            continue
        
        try:
            # Load waveforms
            orig_wav1 = load_audio(file1, audio_dir).to(device)
            orig_wav2 = load_audio(file2, audio_dir).to(device)
            adv_wav1 = load_audio(adv_path1, None).to(device)  # No audio_dir for adv files since full path
            
            # Compute embeddings
            with torch.no_grad():
                orig_emb1 = model.encode_batch(orig_wav1).squeeze(1)
                orig_emb2 = model.encode_batch(orig_wav2).squeeze(1)
                adv_emb1 = model.encode_batch(adv_wav1).squeeze(1)
                
                # Flatten embeddings to ensure 1-D for cosine distance
                orig_emb1_flat = orig_emb1.cpu().numpy().flatten()
                orig_emb2_flat = orig_emb2.cpu().numpy().flatten()
                adv_emb1_flat = adv_emb1.cpu().numpy().flatten()
                
                # Compute similarities
                orig_similarity = 1 - cosine(orig_emb1_flat, orig_emb2_flat)
                adv_similarity = 1 - cosine(adv_emb1_flat, orig_emb2_flat)
                
                # Make predictions
                orig_prediction = 1 if orig_similarity > threshold else 0
                adv_prediction = 1 if adv_similarity > threshold else 0
            
            # Check correctness
            if orig_prediction == label:
                original_correct += 1
            
            if adv_prediction == label:
                adv_correct += 1
            else:
                if orig_prediction == label:  # Attack was successful
                    adv_successful += 1
            
            # Compute SNR
            snr = compute_snr(orig_wav1.cpu(), adv_wav1.cpu())
            snr_values.append(snr)
            
            # Save results
            results['pair_id'].append(i)
            results['label'].append(label)
            results['file1'].append(file1)
            results['file2'].append(file2)
            results['original_similarity'].append(orig_similarity)
            results['adversarial_similarity'].append(adv_similarity)
            results['original_prediction'].append(orig_prediction)
            results['adversarial_prediction'].append(adv_prediction)
            results['attack_success'].append(1 if orig_prediction == label and adv_prediction != label else 0)
            results['snr'].append(snr)
            
            # Store data for EER calculation
            original_labels.append(label)
            original_scores.append(orig_similarity)
            adversarial_labels.append(label)
            adversarial_scores.append(adv_similarity)
            
            total_pairs += 1
            
        except Exception as e:
            print(f"Error processing pair {file1} and {file2}: {e}")
            continue
    
    # Calculate EER for original and adversarial examples
    if len(original_labels) > 0 and len(np.unique(original_labels)) > 1:
        original_eer, original_eer_threshold = calculate_eer(original_labels, original_scores)
    else:
        original_eer, original_eer_threshold = float('nan'), float('nan')
    
    if len(adversarial_labels) > 0 and len(np.unique(adversarial_labels)) > 1:
        adversarial_eer, adversarial_eer_threshold = calculate_eer(adversarial_labels, adversarial_scores)
    else:
        adversarial_eer, adversarial_eer_threshold = float('nan'), float('nan')
    
    # Calculate metrics
    metrics = {
        'original_accuracy': original_correct / total_pairs if total_pairs > 0 else 0,
        'adversarial_accuracy': adv_correct / total_pairs if total_pairs > 0 else 0,
        'attack_success_rate': adv_successful / original_correct if original_correct > 0 else 0,
        'average_snr': np.mean(snr_values) if snr_values else 0,
        'original_eer': original_eer,
        'original_eer_threshold': original_eer_threshold,
        'adversarial_eer': adversarial_eer,
        'adversarial_eer_threshold': adversarial_eer_threshold,
        'results_df': pd.DataFrame(results)
    }
    
    return metrics

def visualize_results(metrics, output_dir):
    """Visualize attack results and save plots"""
    os.makedirs(output_dir, exist_ok=True)
    results_df = metrics['results_df']
    
    # 1. Plot original vs adversarial similarity
    plt.figure(figsize=(10, 6))
    plt.scatter(results_df['original_similarity'], results_df['adversarial_similarity'], 
                c=results_df['attack_success'], cmap='coolwarm', alpha=0.7)
    plt.colorbar(label='Attack Success')
    plt.xlabel('Original Similarity')
    plt.ylabel('Adversarial Similarity')
    plt.title('Original vs Adversarial Similarity')
    plt.grid(True, alpha=0.3)
    plt.savefig(os.path.join(output_dir, 'similarity_comparison.png'), dpi=300)
    
    # 2. Plot SNR distribution
    plt.figure(figsize=(10, 6))
    plt.hist(results_df['snr'], bins=20, alpha=0.7, color='blue')
    plt.axvline(metrics['average_snr'], color='red', linestyle='--', 
                label=f'Average SNR: {metrics["average_snr"]:.2f} dB')
    plt.xlabel('Signal-to-Noise Ratio (dB)')
    plt.ylabel('Frequency')
    plt.title('Distribution of SNR Values')
    plt.legend()
    plt.grid(True, alpha=0.3)
    plt.savefig(os.path.join(output_dir, 'snr_distribution.png'), dpi=300)
    
    # 3. Plot attack success rate by original similarity
    plt.figure(figsize=(10, 6))
    # Create bins for similarity
    bins = np.linspace(0, 1, 11)
    results_df['similarity_bin'] = pd.cut(results_df['original_similarity'], bins)
    
    # Calculate success rate per bin
    success_by_bin = results_df.groupby('similarity_bin')['attack_success'].mean()
    count_by_bin = results_df.groupby('similarity_bin').size()
    
    # Plot
    ax = success_by_bin.plot(kind='bar', figsize=(12, 6), color='skyblue')
    plt.xlabel('Original Similarity Range')
    plt.ylabel('Attack Success Rate')
    plt.title('Attack Success Rate by Original Similarity')
    plt.xticks(rotation=45)
    
    # Add sample count as text on bars
    for i, (success, count) in enumerate(zip(success_by_bin, count_by_bin)):
        if not np.isnan(success):  # Skip empty bins
            ax.text(i, success + 0.05, f'n={count}', ha='center')
    
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, 'success_by_similarity.png'), dpi=300)
    
    # 4. Plot DET curve for original and adversarial examples
    if not np.isnan(metrics.get('original_eer', float('nan'))) and not np.isnan(metrics.get('adversarial_eer', float('nan'))):
        plt.figure(figsize=(10, 6))
        
        # Get original and adversarial labels and scores
        original_labels = results_df['label'].values
        original_scores = results_df['original_similarity'].values
        adversarial_labels = results_df['label'].values
        adversarial_scores = results_df['adversarial_similarity'].values
        
        # Calculate FRR and FAR for different thresholds
        thresholds = np.linspace(0, 1, 100)
        original_frr = []
        original_far = []
        adversarial_frr = []
        adversarial_far = []
        
        for t in thresholds:
            # Original
            original_predictions = (original_scores >= t).astype(int)
            original_frr.append(np.sum((original_predictions == 0) & (original_labels == 1)) / max(1, np.sum(original_labels == 1)))
            original_far.append(np.sum((original_predictions == 1) & (original_labels == 0)) / max(1, np.sum(original_labels == 0)))
            
            # Adversarial
            adversarial_predictions = (adversarial_scores >= t).astype(int)
            adversarial_frr.append(np.sum((adversarial_predictions == 0) & (adversarial_labels == 1)) / max(1, np.sum(adversarial_labels == 1)))
            adversarial_far.append(np.sum((adversarial_predictions == 1) & (adversarial_labels == 0)) / max(1, np.sum(adversarial_labels == 0)))
        
        # Plot DET curves
        plt.plot(original_far, original_frr, 'b-', label=f'Original (EER={metrics["original_eer"]:.4f})')
        plt.plot(adversarial_far, adversarial_frr, 'r-', label=f'Adversarial (EER={metrics["adversarial_eer"]:.4f})')
        
        # Add EER points
        plt.plot([metrics['original_eer']], [metrics['original_eer']], 'bo', markersize=8)
        plt.plot([metrics['adversarial_eer']], [metrics['adversarial_eer']], 'ro', markersize=8)
        
        # Plot settings
        plt.xscale('log')
        plt.yscale('log')
        plt.xlim([0.01, 1])
        plt.ylim([0.01, 1])
        plt.xlabel('False Acceptance Rate (FAR)')
        plt.ylabel('False Rejection Rate (FRR)')
        plt.title('Detection Error Tradeoff (DET) Curve')
        plt.grid(True, alpha=0.3, which='both')
        plt.legend()
        plt.tight_layout()
        plt.savefig(os.path.join(output_dir, 'det_curve.png'), dpi=300)
    
    # Save results to CSV
    results_df.to_csv(os.path.join(output_dir, 'attack_results.csv'), index=False)

def main():
    parser = argparse.ArgumentParser(description='Evaluate PGD Attack on SpeechBrain Speaker Verification Model')
    parser.add_argument('--model', type=str, default="speechbrain/spkrec-xvect-voxceleb", 
                        help='SpeechBrain model path or name')
    parser.add_argument('--pairs_file', type=str, default="data/veri_test.txt", 
                        help='File containing verification pairs')
    parser.add_argument('--audio_dir', type=str, default="data/wav", 
                        help='Directory containing original audio files')
    parser.add_argument('--adv_dir', type=str, default="adversarial_examples", 
                        help='Directory containing adversarial examples')
    parser.add_argument('--output_dir', type=str, default="evaluation_results", 
                        help='Directory to save evaluation results')
    parser.add_argument('--threshold', type=float, default=0.5, 
                        help='Similarity threshold for verification')
    parser.add_argument('--device', type=str, default="cuda" if torch.cuda.is_available() else "cpu", 
                        help='Device to run the evaluation on')
    parser.add_argument('--max_pairs', type=int, default=None,
                        help='Maximum number of pairs to evaluate')
    
    args = parser.parse_args()
    
    # Print configuration
    print("PGD Attack Evaluation Configuration:")
    print(f"  Model: {args.model}")
    print(f"  Pairs file: {args.pairs_file}")
    print(f"  Audio directory: {args.audio_dir}")
    print(f"  Adversarial directory: {args.adv_dir}")
    print(f"  Output directory: {args.output_dir}")
    print(f"  Threshold: {args.threshold}")
    print(f"  Device: {args.device}")
    print(f"  Max pairs: {args.max_pairs if args.max_pairs else 'All'}")
    
    # Check if necessary directories and files exist
    if not os.path.exists(args.audio_dir):
        print(f"Error: Audio directory '{args.audio_dir}' does not exist.")
        return
    
    if not os.path.exists(args.adv_dir):
        print(f"Error: Adversarial examples directory '{args.adv_dir}' does not exist.")
        return
    
    if not os.path.exists(args.pairs_file):
        print(f"Error: Pairs file '{args.pairs_file}' does not exist.")
        return
    
    # Load the SpeechBrain model
    print(f"Loading model: {args.model}")
    try:
        model = EncoderClassifier.from_hparams(source=args.model, savedir="pretrained_models", 
                                            run_opts={"device": args.device})
        print("Model loaded successfully")
    except Exception as e:
        print(f"Error loading model: {e}")
        return
    
    # Evaluate attack
    print("Evaluating adversarial examples...")
    metrics = evaluate_attack(model, args.pairs_file, args.audio_dir, args.adv_dir, 
                            args.device, args.threshold, args.max_pairs)
    
    # Print metrics
    print(f"Original model accuracy: {metrics['original_accuracy']:.4f}")
    print(f"Adversarial model accuracy: {metrics['adversarial_accuracy']:.4f}")
    print(f"Attack success rate: {metrics['attack_success_rate']:.4f}")
    print(f"Average SNR: {metrics['average_snr']:.2f} dB")
    
    if 'original_eer' in metrics and not np.isnan(metrics['original_eer']):
        print(f"Original EER: {metrics['original_eer']:.4f}")
        print(f"Adversarial EER: {metrics['adversarial_eer']:.4f}")
    
    # Visualize results
    print("Generating visualizations...")
    visualize_results(metrics, args.output_dir)
    print(f"Results saved to {args.output_dir}")

if __name__ == "__main__":
    main()
